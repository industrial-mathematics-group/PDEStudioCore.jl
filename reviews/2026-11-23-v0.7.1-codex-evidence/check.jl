using PDEStudioCore, JLD2, Logging
const q=create_param_dict(:k=>"run", :obsolete=>1)
fresh() = (set_save_path!(mktempdir()); joinpath(get_save_path(),"data"))
save() = save_sim_data(create_sim_data([0.,1.],[7.,7.],q))
with_logger(NullLogger()) do
    println("package ",pkgversion(PDEStudioCore))
    dir=fresh()
    good=save()
    bad=joinpath(dir,"partial_"*"0"^64*".jld2")
    cp(good,bad)
    jldopen(f->delete!(f,"raw"),bad,"a+")
    run(`touch -t 202001010000 $good`)
    tidy_sim_data()
    println("cleanup: valid file=",isfile(good)," usable run=",does_sim_data_exist(q)," partial has raw=",jldopen(f->haskey(f,"raw"),bad))
    dir=fresh()
    file=save()
    stage=mkpath(joinpath(dir,".rehash-0"))
    mv(file,joinpath(stage,basename(file)))
    rehash_sim_data()
    println("all files staged: recovered=",does_sim_data_exist(q))
    dir=fresh()
    file=save()
    link=joinpath(dir,"alias.jld2")
    symlink(basename(file),link)
    rehash_sim_data(;filter_pairs=Dict(:k=>"unmatched"))
    println("unmatched filter: link preserved=",islink(link))
    dir=fresh()
    file=save()
    external=joinpath(dirname(dir),"shared.jld2")
    mv(file,external)
    symlink(relpath(external,dir),file)
    outputs=rehash_sim_data(;remove_keys=[:obsolete])
    println("external relative link: rewrites=",length(outputs)," new run=",does_sim_data_exist(create_param_dict(:k=>"run"))," target preserved=",isfile(external))
    dir=fresh()
    file=save()
    backup=mkpath(joinpath(dir,".rehash-backup"))
    write(joinpath(backup,"notes.txt"),"private working notes")
    rehash_sim_data(file)
    println("single-file operation: unrelated notes stayed=",isfile(joinpath(backup,"notes.txt"))," moved into data=",isfile(joinpath(dir,"notes.txt")))
end
